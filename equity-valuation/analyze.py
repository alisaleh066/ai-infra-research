"""analyze.py — one-command automated equity research workup for ANY US-listed ticker.

    python analyze.py NVDA

Pulls all financials once (SEC EDGAR + Yahoo) and runs a battery of recognized techniques —
ratios + DuPont, ROIC vs WACC, Piotroski F-Score, Altman Z-Score, Beneish M-Score, Sloan
accruals, and a reverse DCF — then writes a research note (output/<TICKER>_research.md) and an
Excel workbook (output/<TICKER>_analysis.xlsx) and prints a summary. Not investment advice.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill

import data as datamod
import analysis as an

OUT = Path(__file__).resolve().parent / "output"


def _wacc_beta(fund, price):
    """Self-contained CAPM WACC + beta (clamped) for the analysis layer."""
    y = fund["years"][-1]
    shares = fund.get("shares", {}).get(y)
    debt = (fund.get("long_term_debt", {}).get(y) or 0) + (fund.get("short_term_debt", {}).get(y) or 0)
    beta = 1.10
    pr_hist = datamod.fetch_price(fund["ticker"])["history"]
    if pr_hist:
        spy = datamod.fetch_price("SPY")["history"]
        if spy:
            import numpy as np
            sd, md = dict(pr_hist), dict(spy)
            dates = sorted(set(sd) & set(md))
            if len(dates) > 60:
                s = np.array([sd[d] for d in dates]); m = np.array([md[d] for d in dates])
                sr = np.diff(s) / s[:-1]; mr = np.diff(m) / m[:-1]
                if np.var(mr) > 0:
                    beta = float(np.cov(sr, mr)[0, 1] / np.var(mr))
    beta = max(0.5, min(beta, 2.0))
    ke = 0.043 + beta * 0.05
    kd_at = 0.05 * (1 - 0.21)
    if price and shares:
        mc = price * shares
        wacc = (mc * ke + debt * kd_at) / (mc + debt) if (mc + debt) else ke
        return round(wacc, 4), round(beta, 3), mc
    return round(ke, 4), round(beta, 3), None


def analyze(ticker: str) -> dict:
    OUT.mkdir(exist_ok=True)
    fund = datamod.fetch_fundamentals(ticker)
    pr = datamod.fetch_price(ticker)
    price = pr["price"]
    wacc, beta, market_cap = _wacc_beta(fund, price)

    rep = {
        "ticker": fund["ticker"], "company": fund["name"], "fiscal_years": fund["years"],
        "price": price, "beta": beta, "wacc": wacc, "market_cap": market_cap,
        "ratios": an.ratios(fund), "dupont": an.dupont(fund),
        "roic_vs_wacc": an.roic_vs_wacc(fund, wacc),
        "piotroski": an.piotroski_f(fund), "altman_z": an.altman_z(fund, market_cap),
        "beneish_m": an.beneish_m(fund), "sloan": an.sloan_accruals(fund),
        "reverse_dcf": an.reverse_dcf(fund, price, wacc),
        "data_flags": fund["missing_flags"],
    }
    _write_md(rep)
    _write_xlsx(rep)
    _print(rep)
    return rep


# --------------------------------------------------------------------------- formatting
def _p(x, dp=1):
    return "n/a" if x is None else f"{x*100:.{dp}f}%"


def _x(x, dp=2):
    return "n/a" if x is None else f"{x:.{dp}f}x"


def _verdict(rep) -> tuple[list[str], list[str]]:
    green, red = [], []
    r = rep["ratios"]; rw = rep["roic_vs_wacc"]; pf = rep["piotroski"]
    az = rep["altman_z"]; bm = rep["beneish_m"]; sl = rep["sloan"]
    if rw.get("creates_value"): green.append("ROIC exceeds WACC (creates value)")
    elif rw.get("value_spread") is not None: red.append("ROIC below WACC (destroys value)")
    if pf.get("score") is not None:
        (green if pf["score"] >= 7 else red if pf["score"] <= 3 else green).append(
            f"Piotroski F-Score {pf['score']}/9 ({pf.get('verdict')})")
    if az.get("zone") == "safe": green.append(f"Altman Z {az['z']} (safe)")
    elif az.get("zone") == "distress": red.append(f"Altman Z {az['z']} (distress zone)")
    if bm.get("flag") == "possible manipulation": red.append(f"Beneish M {bm['m']} (earnings-quality flag)")
    elif bm.get("flag") == "clean": green.append(f"Beneish M {bm['m']} (clean)")
    if sl.get("quality") == "low": red.append("High accruals (low earnings quality)")
    elif sl.get("quality") in ("high", "ok"): green.append("Accruals OK (cash-backed earnings)")
    if r.get("net_debt_to_ebitda") is not None and r["net_debt_to_ebitda"] > 4:
        red.append(f"High leverage (net debt/EBITDA {r['net_debt_to_ebitda']:.1f}x)")
    return green, red


def _write_md(rep) -> None:
    r, dp, rw = rep["ratios"], rep["dupont"], rep["roic_vs_wacc"]
    pf, az, bm, sl, rd = rep["piotroski"], rep["altman_z"], rep["beneish_m"], rep["sloan"], rep["reverse_dcf"]
    green, red = _verdict(rep)
    lines = [
        f"# {rep['company']} ({rep['ticker']}) — Automated Research Note",
        "",
        f"*FY {rep['fiscal_years']} · SEC EDGAR + Yahoo · WACC {_p(rep['wacc'],1)} (beta {rep['beta']}). "
        "Generated by `analyze.py`. Not investment advice.*",
        "",
        "## Bottom line",
        "**Positives:** " + ("; ".join(green) if green else "—"),
        "",
        "**Watch-outs:** " + ("; ".join(red) if red else "—"),
        "",
        "## Profitability & returns",
        f"- Gross margin **{_p(r['gross_margin'])}** · Operating margin **{_p(r['operating_margin'])}** · Net margin **{_p(r['net_margin'])}**",
        f"- ROA **{_p(r['roa'])}** · ROE **{_p(r['roe'])}**",
        f"- **ROIC {_p(rw['roic'])} vs WACC {_p(rw['wacc'])} → spread {_p(rw['value_spread'])}** "
        f"({'value-creating' if rw.get('creates_value') else 'not creating value'})",
        f"- DuPont ROE = net margin {_p(dp['net_margin'])} × asset turnover {_x(dp['asset_turnover'])} × "
        f"equity multiplier {_x(dp['equity_multiplier'])} = **{_p(dp['roe'])}**",
        "",
        "## Quality & forensic screens",
        f"- **Piotroski F-Score: {pf.get('score')}/9** ({pf.get('verdict','n/a')}) — 9-point fundamental strength.",
        f"- **Altman Z-Score: {az.get('z','n/a')}** ({az.get('zone','n/a')}) — distress risk.",
        f"- **Beneish M-Score: {bm.get('m','n/a')}** ({bm.get('flag', bm.get('note','n/a'))}) — earnings-manipulation screen.",
        f"- **Sloan accrual ratio: {sl.get('accrual_ratio','n/a')}** ({sl.get('quality','n/a')} earnings quality).",
        "",
        "## Balance-sheet health",
        f"- Current ratio **{_x(r['current_ratio'])}** · Debt/Equity **{_x(r['debt_to_equity'])}** · "
        f"Net debt/EBITDA **{_x(r['net_debt_to_ebitda'])}**",
        "",
        "## Market-implied expectations (reverse DCF)",
        f"- At the current price, the market implies a **flat 5-yr revenue growth of "
        f"{_p(rd['implied_growth']) if rd.get('implied_growth') is not None else 'n/a'}** "
        f"(WACC {_p(rep['wacc'])}). Ask: is that beatable or heroic?",
        "",
        "## Method & honesty",
        "Fundamentals are audited 10-K values from SEC EDGAR; any line a filing doesn't provide is "
        "shown as n/a, never fabricated. Scores use standard published formulas (Piotroski 2000, "
        "Altman 1968, Beneish 1999, Sloan 1996). This is a screen, not a recommendation.",
    ]
    if rep["data_flags"]:
        lines.append(f"\n*Data flags (missing core lines): {', '.join(rep['data_flags'])}.*")
    (OUT / f"{rep['ticker']}_research.md").write_text("\n".join(lines), encoding="utf-8")


def _write_xlsx(rep) -> None:
    wb = Workbook(); ws = wb.active; ws.title = "Analysis"
    ws.column_dimensions["A"].width = 34; ws.column_dimensions["B"].width = 16
    bold = Font(bold=True)
    ws["A1"] = f"{rep['company']} ({rep['ticker']}) — analysis"; ws["A1"].font = Font(bold=True, size=14)
    r, dp, rw = rep["ratios"], rep["dupont"], rep["roic_vs_wacc"]
    rows = [
        ("PROFITABILITY", ""),
        ("Gross margin", r["gross_margin"]), ("Operating margin", r["operating_margin"]),
        ("Net margin", r["net_margin"]), ("ROA", r["roa"]), ("ROE", r["roe"]),
        ("ROIC", rw["roic"]), ("WACC", rw["wacc"]), ("ROIC - WACC spread", rw["value_spread"]),
        ("DUPONT", ""),
        ("Net margin", dp["net_margin"]), ("Asset turnover", dp["asset_turnover"]),
        ("Equity multiplier", dp["equity_multiplier"]), ("ROE (DuPont)", dp["roe"]),
        ("QUALITY / FORENSIC", ""),
        ("Piotroski F-Score (/9)", rep["piotroski"].get("score")),
        ("Altman Z-Score", rep["altman_z"].get("z")),
        ("Beneish M-Score", rep["beneish_m"].get("m")),
        ("Sloan accrual ratio", rep["sloan"].get("accrual_ratio")),
        ("HEALTH", ""),
        ("Current ratio", r["current_ratio"]), ("Debt / Equity", r["debt_to_equity"]),
        ("Net debt / EBITDA", r["net_debt_to_ebitda"]),
        ("MARKET-IMPLIED", ""),
        ("Reverse-DCF implied growth", rep["reverse_dcf"].get("implied_growth")),
    ]
    row = 3
    for label, val in rows:
        ws[f"A{row}"] = label
        if val == "":
            ws[f"A{row}"].font = bold; ws[f"A{row}"].fill = PatternFill("solid", fgColor="E2E8F0")
        elif val is not None:
            ws[f"B{row}"] = round(val, 4)
        else:
            ws[f"B{row}"] = "n/a"
        row += 1
    OUT.mkdir(exist_ok=True)
    wb.save(OUT / f"{rep['ticker']}_analysis.xlsx")


def _print(rep) -> None:
    green, red = _verdict(rep)
    print(f"\n{rep['company']} ({rep['ticker']}) — research workup   FY {rep['fiscal_years']}")
    rw = rep["roic_vs_wacc"]
    print(f"  ROIC {_p(rw['roic'])} vs WACC {_p(rw['wacc'])}  (spread {_p(rw['value_spread'])})")
    print(f"  Piotroski F {rep['piotroski'].get('score')}/9 | Altman Z {rep['altman_z'].get('z')} "
          f"({rep['altman_z'].get('zone','n/a')}) | Beneish M {rep['beneish_m'].get('m')} "
          f"({rep['beneish_m'].get('flag','n/a')}) | accruals {rep['sloan'].get('quality','n/a')}")
    rd = rep["reverse_dcf"].get("implied_growth")
    print(f"  Reverse-DCF implied 5-yr growth: {_p(rd) if rd is not None else 'n/a'}")
    print(f"  + {len(green)} positives / {len(red)} watch-outs")
    print(f"  Wrote: {OUT / (rep['ticker'] + '_research.md')}")
    print(f"  Wrote: {OUT / (rep['ticker'] + '_analysis.xlsx')}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Automated equity research workup.")
    ap.add_argument("ticker")
    args = ap.parse_args()
    try:
        analyze(args.ticker)
    except ValueError as e:
        print(f"\n{e}")
        raise SystemExit(1)
